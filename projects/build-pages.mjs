import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

const directory = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(join(directory, 'app.js'), 'utf8');
const metadata = source.slice(0, source.indexOf('const $ ='));
const grouping = source.slice(source.indexOf('const collections='), source.indexOf('const groups='));
const context = {};
vm.runInNewContext(`${metadata}\n${grouping}\nglobalThis.catalog = projects;`, context);
const catalog = JSON.parse(JSON.stringify(context.catalog));
const htmlEscape = text => String(text).replace(/[&<>"']/g, char => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;'
}[char]));

writeFileSync(join(directory, 'project-catalog.js'),
  `/* Generated by build-pages.mjs from app.js. */\nwindow.PROJECT_CATALOG = ${JSON.stringify(catalog, null, 2)};\n`);

for (const project of catalog) {
  const title = htmlEscape(project.title);
  const description = htmlEscape(project.desc);
  writeFileSync(join(directory, `${project.id}.html`), `<!doctype html>
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <meta name="theme-color" content="#f9f7ef">
  <meta name="description" content="${description}">
  <title>${title} · Chengmu She</title>
  <link rel="icon" href="../assets/little-flower.svg" type="image/svg+xml">
  <link rel="stylesheet" href="./styles.css">
  <link rel="stylesheet" href="./app-pages.css?v=20261104f">
  <link rel="stylesheet" href="./project-guide.css?v=20261106b">
  <link rel="stylesheet" href="./project-flows.css?v=20261106b">
</head>
<body data-project="${project.id}">
  <div id="app"></div>
  <script defer src="./project-catalog.js?v=20261104f"></script>
  <script defer src="./project-guide.js?v=20261106a"></script>
  <script defer src="./connections.js"></script>
  <script defer src="./api.js?v=20261104f"></script>
  <script defer src="./project-features.js?v=20261104f"></script>
  <script defer src="./project-features-more.js?v=20261104f"></script>
  <script defer src="./project-flows.js?v=20261106b"></script>
  <script defer src="./project-flows-more.js?v=20261106b"></script>
  <script defer src="./app-pages.js?v=20261106a"></script>
  <script defer src="./standalone.js?v=20261106a"></script>
</body>
</html>
`);
}
console.log(`Generated ${catalog.length} standalone project pages.`);
